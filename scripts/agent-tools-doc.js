#!/usr/bin/env node
// Generate the tool catalogue of docs/guide/agent-model.md from the deck tool
// specs (src/server/deck-tools.js), so the page always matches the code.
//   node scripts/agent-tools-doc.js          rewrite the generated section
//   node scripts/agent-tools-doc.js --check  exit 1 when the page is out of date

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MUTATING_TOOLS, SLIDE_SCOPED_OPS, deckToolSpecs, mcpToolSpecs } from "../src/server/deck-tools.js";

export const DOC_PATH = path.join(path.dirname(fileURLToPath(import.meta.url)), "../docs/guide/agent-model.md");
export const START = "<!-- tools:start: generated by `npm run docs:tools`, do not edit by hand -->";
export const END = "<!-- tools:end -->";

// Plain table text: escape the cell separator and HTML, keep one line.
const cell = (text) => String(text ?? "").replace(/\s+/g, " ").replace(/\|/g, "\\|").replace(/</g, "&lt;").trim();
const yes = (flag) => (flag ? "✓" : "–");

function typeOf(schema = {}) {
  if (schema.enum) return schema.enum.map((v) => `\`${v}\``).join(", ");
  const types = [schema.type].flat().filter(Boolean);
  let out = types.join(" or ") || "any";
  if (Number.isFinite(schema.minimum)) out += ` ≥ ${schema.minimum}`;
  return out;
}

function parameterTable(spec) {
  const props = Object.entries(spec.parameters?.properties || {});
  if (!props.length) return "No parameters.";
  const required = new Set(spec.parameters.required || []);
  return [
    "| Parameter | Type | Required | Description |",
    "|---|---|---|---|",
    ...props.map(([name, schema]) => `| \`${name}\` | ${cell(typeOf(schema))} | ${yes(required.has(name))} | ${cell(schema.description)} |`),
  ].join("\n");
}

/** The generated Markdown: a summary table, then each tool with its input schema. */
export function renderToolCatalogue() {
  const editorTools = new Set(deckToolSpecs().map((t) => t.name));
  const mutating = new Set(MUTATING_TOOLS);
  const specs = mcpToolSpecs();
  const summary = [
    "| Tool | Changes the deck | Allowed in *This slide* scope | Editor chat | `deckforge mcp` |",
    "|---|---|---|---|---|",
    ...specs.map((s) => {
      const slideScope = !mutating.has(s.name) || SLIDE_SCOPED_OPS.has(s.name);
      return `| [\`${s.name}\`](#tool-${s.name.replace(/_/g, "-")}) | ${yes(mutating.has(s.name))} | ${editorTools.has(s.name) ? yes(slideScope) : "–"} | ${yes(editorTools.has(s.name))} | ✓ |`;
    }),
  ].join("\n");
  const details = specs.map((s) => `### \`${s.name}\` {#tool-${s.name.replace(/_/g, "-")}}\n\n${cell(s.description)}\n\n${parameterTable(s)}`);
  return [START, "", summary, "", ...details.flatMap((d) => [d, ""]), END].join("\n");
}

/** Replace the generated section of the page. */
export function updateDoc(source) {
  const start = source.indexOf(START);
  const end = source.indexOf(END);
  if (start === -1 || end === -1 || end < start) throw new Error(`Missing the ${START} … ${END} markers in ${DOC_PATH}`);
  return source.slice(0, start) + renderToolCatalogue() + source.slice(end + END.length);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const current = fs.readFileSync(DOC_PATH, "utf8");
  const next = updateDoc(current);
  if (process.argv.includes("--check")) {
    if (next !== current) {
      console.error(`${path.relative(process.cwd(), DOC_PATH)} is out of date: run npm run docs:tools`);
      process.exit(1);
    }
  } else if (next !== current) {
    fs.writeFileSync(DOC_PATH, next);
    console.log(`Updated ${path.relative(process.cwd(), DOC_PATH)}`);
  }
}
